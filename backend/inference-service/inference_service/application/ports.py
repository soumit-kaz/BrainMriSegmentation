from collections.abc import AsyncGenerator
from datetime import datetime
from pathlib import Path
from typing import TYPE_CHECKING, Any, Protocol

import numpy as np

from inference_service.domain.segmentation_job import JobStatus, ModelInformation, SegmentationJob, SegmentationSummary

if TYPE_CHECKING:
    from nibabel.nifti1 import Nifti1Image
    from segmentation_core.evaluation import SlidingWindowPredictor


class SegmentationJobRepository(Protocol):
    def initialize_schema(self) -> None: ...

    def is_available(self) -> bool: ...

    def add_job(self, job: SegmentationJob) -> None: ...

    def get_job(self, job_id: str) -> SegmentationJob: ...

    def get_jobs(self, limit: int) -> list[SegmentationJob]: ...

    def get_reusable_job(self, input_hash: str) -> SegmentationJob | None: ...

    def get_job_count(self, statuses: frozenset[JobStatus]) -> int: ...

    def get_queue_position(self, job: SegmentationJob) -> int: ...

    def mark_processing(self, job_id: str) -> SegmentationJob: ...

    def mark_completed(self, job_id: str, summary: SegmentationSummary) -> SegmentationJob: ...

    def mark_failed(self, job_id: str, error_message: str) -> SegmentationJob: ...

    def delete_job(self, job_id: str) -> None: ...

    def get_expired_job_ids(self, completed_before: datetime) -> list[str]: ...


class JobQueue(Protocol):
    def is_available(self) -> bool: ...

    def ensure_consumer_group(self) -> None: ...

    def add_job(self, job_id: str) -> None: ...

    def get_next_job(self, block_milliseconds: int) -> tuple[str, str] | None: ...

    def get_stalled_job(self, minimum_idle_milliseconds: int) -> tuple[str, str] | None: ...

    def acknowledge(self, message_id: str) -> None: ...


class JobEventPublisher(Protocol):
    def publish(self, job_id: str, event: dict[str, Any]) -> None: ...


class JobEventSubscriber(Protocol):
    def get_events(self, job_id: str) -> AsyncGenerator[dict[str, Any], None]: ...


class RateLimiter(Protocol):
    def is_allowed(self, client_key: str, limit_per_minute: int) -> bool: ...


class WorkerStatusStore(Protocol):
    def set_model_information(self, model_information: ModelInformation) -> None: ...

    def get_model_information(self) -> ModelInformation | None: ...

    def add_processing_duration(self, duration_seconds: float) -> None: ...

    def get_average_processing_seconds(self, default_seconds: float) -> float: ...


class ScanStorage(Protocol):
    def create_staging_directory(self) -> str: ...

    def get_staging_path(self, staging_directory_name: str, file_name: str) -> Path: ...

    def remove_staging_directory(self, staging_directory_name: str) -> None: ...

    def promote_staging_directory(self, staging_directory_name: str, job_id: str) -> None: ...

    def get_input_path(self, job_id: str, suffix: str) -> Path: ...

    def save_results(self, job_id: str, preview_volumes: dict[str, np.ndarray], predicted_mask: np.ndarray,
                     reference_image: "Nifti1Image") -> None: ...

    def get_preview_volume(self, job_id: str, preview_name: str) -> np.ndarray: ...

    def get_mask_path(self, job_id: str) -> Path: ...

    def delete_job_files(self, job_id: str) -> None: ...


class SliceRenderer(Protocol):
    def get_image_png(self, volume: np.ndarray, slice_index: int) -> bytes: ...

    def get_mask_png(self, mask_volume: np.ndarray, slice_index: int, color: tuple[int, int, int]) -> bytes: ...


class ModelProvider(Protocol):
    def get_predictor(self) -> tuple["SlidingWindowPredictor", dict[str, Any]]: ...

    def get_information(self) -> ModelInformation: ...

    def get_device_name(self) -> str: ...
